const TILE_COLORS = Object.freeze({
  '.': '#000000',
  d: '#702426',
  r: '#b83c3c',
  l: '#f46a64',
  g: '#ffff55',
  s: '#9b7c22',
});

const ROPE = [
  '...dd...',
  'll..rr..',
  'rll..rr.',
  'drll..rr',
  '.drll..r',
  '..drll..',
  'r..drl..',
  'dr...dd.',
];

const CORNER = [
  'gggggggs',
  'g.....ss',
  'g.ggg.ss',
  'g.g.g.ss',
  'g.ggg.ss',
  'g.....ss',
  'gsssssss',
  'ssssssss',
];

const GLYPH_COLUMNS = 16;
const GLYPH_CHARACTERS = Object.keys(GLYPHS);
const GLYPH_INDEX = new Map(GLYPH_CHARACTERS.map((character, index) => [character, index]));
const glyphAtlases = new Map();
let edgeAtlas;

function createAtlas(columns, rows) {
  const canvas = document.createElement('canvas');
  canvas.width = columns * TILE_SIZE;
  canvas.height = rows * TILE_SIZE;
  const ctx = canvas.getContext('2d', { alpha: true, willReadFrequently: true });
  ctx.imageSmoothingEnabled = false;
  return { canvas, ctx };
}

function getGlyphAtlas(color) {
  let atlas = glyphAtlases.get(color);
  if (atlas) return atlas;
  const { canvas, ctx } = createAtlas(GLYPH_COLUMNS, Math.ceil(GLYPH_CHARACTERS.length / GLYPH_COLUMNS));
  ctx.fillStyle = color;
  GLYPH_CHARACTERS.forEach((character, index) => {
    const glyph = GLYPHS[character];
    const left = (index % GLYPH_COLUMNS) * TILE_SIZE;
    const top = Math.floor(index / GLYPH_COLUMNS) * TILE_SIZE;
    for (let y = 0; y < TILE_SIZE; y += 1) {
      let x = 0;
      while (x < TILE_SIZE) {
        if (!(glyph[y] & (0x80 >> x))) {
          x += 1;
          continue;
        }
        const start = x;
        while (x < TILE_SIZE && glyph[y] & (0x80 >> x)) x += 1;
        ctx.fillRect(left + start, top + y, x - start, 1);
      }
    }
  });
  atlas = canvas;
  glyphAtlases.set(color, atlas);
  return atlas;
}

function getEdgeAtlas() {
  if (edgeAtlas) return edgeAtlas;
  const { canvas, ctx } = createAtlas(3, 1);
  for (let tileIndex = 0; tileIndex < 3; tileIndex += 1) {
    const bitmap = tileIndex === 2 ? CORNER : ROPE;
    for (let y = 0; y < TILE_SIZE; y += 1) {
      for (let x = 0; x < TILE_SIZE; x += 1) {
        ctx.fillStyle = TILE_COLORS[tileIndex === 1 ? bitmap[TILE_SIZE - 1 - x][y] : bitmap[y][x]];
        ctx.fillRect(tileIndex * TILE_SIZE + x, y, 1, 1);
      }
    }
  }
  edgeAtlas = canvas;
  return edgeAtlas;
}

function normalizeText(text) {
  return String(text)
    .replace(/\r\n?/g, '\n')
    .replace(/[\u2018\u2019]/g, "'")
    .replace(/[\u201c\u201d]/g, '"')
    .replace(/[\u2010-\u2015\u2212]/g, '-')
    .replace(/\u2026/g, '...')
    .replace(/[\u00b7\u2022]/g, '.')
    .replace(/\u2190/g, '<')
    .replace(/\u2192/g, '>')
    .replace(/\u2191/g, '^')
    .replace(/\u2193/g, 'V')
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toUpperCase();
}

export function wrapText(text, maxColumns) {
  if (!Number.isInteger(maxColumns) || maxColumns < 1) {
    throw new RangeError('Text width must be a positive whole number of cells.');
  }

  const lines = [];
  for (const paragraph of normalizeText(text).split('\n')) {
    let line = '';
    for (let word of paragraph.trim().split(/\s+/).filter(Boolean)) {
      if (line && line.length + 1 + word.length > maxColumns) {
        lines.push(line);
        line = '';
      }
      while (word.length > maxColumns) {
        lines.push(word.slice(0, maxColumns));
        word = word.slice(maxColumns);
      }
      if (word) line += `${line ? ' ' : ''}${word}`;
    }
    if (line || !paragraph.trim()) lines.push(line);
  }
  return lines;
}

function requireCells(...values) {
  if (values.some((value) => !Number.isInteger(value))) {
    throw new RangeError('Tile geometry must use whole cells.');
  }
}

export function createTilePainter(ctx) {
  ctx.imageSmoothingEnabled = false;

  function tile(bitmap, column, row, rotate = false) {
    const index = bitmap === CORNER ? 2 : rotate ? 1 : 0;
    ctx.drawImage(getEdgeAtlas(), index * TILE_SIZE, 0, TILE_SIZE, TILE_SIZE, column * TILE_SIZE, row * TILE_SIZE, TILE_SIZE, TILE_SIZE);
    ctx.fillStyle = TILE_COLORS[rotate ? bitmap[0][TILE_SIZE - 1] : bitmap[TILE_SIZE - 1][TILE_SIZE - 1]];
  }

  function horizontal(column, row, columns) {
    requireCells(column, row, columns);
    for (let x = 0; x < columns; x += 1) tile(ROPE, column + x, row);
  }

  function vertical(column, row, rows) {
    requireCells(column, row, rows);
    for (let y = 0; y < rows; y += 1) tile(ROPE, column, row + y, true);
  }

  function corner(column, row) {
    requireCells(column, row);
    tile(CORNER, column, row);
  }

  return {
    text(text, column, row, color = '#ffffff', maxColumns = Infinity) {
      requireCells(column, row);
      const characters = normalizeText(text).split('\n')[0].slice(0, Math.max(0, maxColumns));
      ctx.fillStyle = color;
      const atlas = getGlyphAtlas(color);
      for (let i = 0; i < characters.length; i += 1) {
        const index = GLYPH_INDEX.get(characters[i]) ?? GLYPH_INDEX.get('?');
        ctx.drawImage(atlas, (index % GLYPH_COLUMNS) * TILE_SIZE, Math.floor(index / GLYPH_COLUMNS) * TILE_SIZE, TILE_SIZE, TILE_SIZE, (column + i) * TILE_SIZE, row * TILE_SIZE, TILE_SIZE, TILE_SIZE);
      }
    },
    frame(column, row, columns, rows) {
      requireCells(column, row, columns, rows);
      if (columns < 2 || rows < 2) {
        throw new RangeError('A tile frame needs at least two columns and two rows.');
      }
      horizontal(column + 1, row, columns - 2);
      horizontal(column + 1, row + rows - 1, columns - 2);
      vertical(column, row + 1, rows - 2);
      vertical(column + columns - 1, row + 1, rows - 2);
      corner(column, row);
      corner(column + columns - 1, row);
      corner(column, row + rows - 1);
      corner(column + columns - 1, row + rows - 1);
    },
    horizontal,
    vertical,
    corner,
  };
}
